from sqlalchemy.orm import Session
from app.models.project import ProjectModel
from app.models.user import UserModel

# Должен буквально совпадать с UUID служебного legacy-пользователя, вставленного
# миграцией alembic/versions/0002_users_and_ownership.py — это один и тот же
# "виртуальный владелец" для всех проектов, у которых owner_id был NULL до
# появления авторизации (см. отчёт по задаче, решение №6).
LEGACY_USER_ID = "00000000-0000-0000-0000-000000000001"


def claim_legacy_projects_for_first_user(db: Session, new_user: UserModel) -> None:
    """
    Срабатывает один раз в жизни приложения: сразу после успешной регистрации
    ПЕРВОГО настоящего пользователя (проверка `count_real_users(db) == 0`
    делается в api/auth.py ДО вызова create_user, т.е. до того как new_user
    посчитается "настоящим" пользователем сам). Переводим все проекты,
    принадлежащие служебному legacy-пользователю, на нового — иначе чертежи,
    созданные до появления регистрации, стали бы недостижимы (отфильтрованы
    по owner_id в crud/project.py), хотя физически остались бы в БД.

    Инвариант (важно, если когда-нибудь появятся несколько воркеров/процессов):
    вызывающий код (api/auth.py) делает проверку "это первый пользователь?" и
    сам вызов create_user+эту функцию в рамках одного запроса/одной DB-сессии
    синхронно — при нескольких одновременных процессах два параллельных
    "первых" регистрации теоретически могли бы оба увидеть count==0 до того,
    как любой из них закоммитится (classic check-then-act race). Для текущего
    однопроцессного деплоя это не проблема.
    """
    db.query(ProjectModel).filter(ProjectModel.owner_id == LEGACY_USER_ID).update(
        {"owner_id": new_user.id}
    )
    db.commit()
